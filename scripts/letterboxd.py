#!/usr/bin/env python3
"""Reads Shashank's public Letterboxd diary feed and writes partials/lists-films.hbs
with the five most recent watches (title, rating, date, poster, link).
Run by .github/workflows/letterboxd.yml once a day. Standard library only."""
import html
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from datetime import date
from pathlib import Path

FEED = 'https://letterboxd.com/iamshashank/rss/'
OUT = Path(__file__).resolve().parent.parent / 'partials' / 'lists-films.hbs'
NS = {'lb': 'https://letterboxd.com'}
COUNT = 5

GO = ('<svg class="ls-go" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.7" '
      'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M3.5 8h9M9 4.5 12.5 8 9 11.5"/></svg>')
FILM_ICON = ('<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" '
             'stroke-linejoin="round" aria-hidden="true"><rect x="4" y="3" width="16" height="18" rx="2"/>'
             '<path d="M8 3v18M16 3v18M4 8h4M4 16h4M16 8h4M16 16h4"/></svg>')


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'shaashank.com lists sync (+https://www.shaashank.com)'})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def stars(rating):
    if rating is None:
        return ''
    full = int(rating)
    return '★' * full + ('½' if rating - full >= 0.5 else '')


def entries(xml_bytes):
    root = ET.fromstring(xml_bytes)
    out = []
    for item in root.iter('item'):
        watched = item.findtext('lb:watchedDate', namespaces=NS)
        title = item.findtext('lb:filmTitle', namespaces=NS)
        if not watched or not title:
            continue  # lists and other non-diary items
        rating = item.findtext('lb:memberRating', namespaces=NS)
        desc = item.findtext('description') or ''
        m = re.search(r'<img[^>]+src="([^"]+)"', desc)
        out.append({
            'title': title.strip(),
            'date': date.fromisoformat(watched.strip()),
            'rating': float(rating) if rating else None,
            'link': (item.findtext('link') or '').strip(),
            'poster': m.group(1) if m else '',
        })
    out.sort(key=lambda e: e['date'], reverse=True)
    return out[:COUNT]


def render(items):
    rows = []
    for e in items:
        t = html.escape(e['title'])
        if e['poster'].startswith('https://'):
            pic = '<img class="ls-poster" src="%s" alt="%s poster" loading="lazy" decoding="async">' % (html.escape(e['poster']), t)
        else:
            pic = '<span class="ls-ph ls-ph--poster">%s</span>' % FILM_ICON
        when = 'Watched %d %s' % (e['date'].day, e['date'].strftime('%b'))
        rate = '<span class="ls-rate" aria-label="%s out of 5">%s</span>' % (e['rating'], stars(e['rating'])) if e['rating'] else ''
        rows.append(
            '    <a class="ls-r" href="%s" target="_blank" rel="noopener">\n'
            '      <span class="ls-th" style="--th:120px">%s</span>\n'
            '      <span class="ls-tx"><b>%s</b><span class="ls-sub">%s</span>%s</span>\n'
            '      %s\n'
            '    </a>' % (html.escape(e['link']), pic, t, when, rate, GO))
    return (
        '{{!-- Generated by scripts/letterboxd.py from the Letterboxd diary feed. Do not edit by hand:\n'
        '     it is rewritten every day. --}}\n'
        '<section class="ls-sec" aria-labelledby="ls-films">\n'
        '  <div class="ls-sh">\n'
        '    <h2 id="ls-films">What I’ve been watching</h2>\n'
        '    <a class="ls-more" href="https://letterboxd.com/iamshashank/diary/" target="_blank" rel="noopener">All on Letterboxd<svg class="ls-ar" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M3.5 8h9M9 4.5 12.5 8 9 11.5"/></svg></a>\n'
        '  </div>\n'
        '  <div class="ls-list">\n%s\n  </div>\n'
        '</section>\n' % '\n'.join(rows))


def main():
    items = entries(fetch(FEED))
    if not items:
        print('No diary entries found; leaving the partial unchanged.')
        return 0
    new = render(items)
    old = OUT.read_text() if OUT.exists() else ''
    if new == old:
        print('No change.')
        return 0
    OUT.write_text(new)
    print('Updated %s with %d watches.' % (OUT.name, len(items)))
    return 0


if __name__ == '__main__':
    sys.exit(main())

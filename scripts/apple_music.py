#!/usr/bin/env python3
"""Writes partials/lists-artists.hbs from scripts/artists.json.

For each Apple Music link it asks Apple's public lookup service for the song name,
the official 30-second preview and the cover art. Run daily by
.github/workflows/letterboxd.yml (preview links can change). Standard library only.

To change an artist or song: edit scripts/artists.json. Optional "photo" key
(a file in assets/images/lists/) replaces the cover art with your own picture."""
import html
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / 'scripts' / 'artists.json'
OUT = ROOT / 'partials' / 'lists-artists.hbs'

PLAY = '<svg class="ls-i-play" viewBox="0 0 24 24" aria-hidden="true"><path d="M8 5.5v13a1 1 0 0 0 1.5.86l10.5-6.5a1 1 0 0 0 0-1.72L9.5 4.64A1 1 0 0 0 8 5.5z" fill="currentColor"/></svg>'
PAUSE = '<svg class="ls-i-pause" viewBox="0 0 24 24" aria-hidden="true"><rect x="6.5" y="5" width="4" height="14" rx="1.2" fill="currentColor"/><rect x="13.5" y="5" width="4" height="14" rx="1.2" fill="currentColor"/></svg>'
GO = ('<svg class="ls-go" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" '
      'stroke-linejoin="round" aria-hidden="true"><path d="M3.5 8h9M9 4.5 12.5 8 9 11.5"/></svg>')


def lookup(url):
    """Return the track for a music.apple.com song or single link."""
    path = urllib.parse.urlparse(url).path.strip('/').split('/')
    country = path[0] if len(path[0]) == 2 else 'us'
    kind, ident = path[1], path[-1]
    q = urllib.parse.parse_qs(urllib.parse.urlparse(url).query)
    if 'i' in q:  # album link pointing at one track
        kind, ident = 'song', q['i'][0]
    params = {'id': ident, 'country': country}
    if kind == 'album':
        params['entity'] = 'song'
    req = urllib.request.Request('https://itunes.apple.com/lookup?' + urllib.parse.urlencode(params),
                                 headers={'User-Agent': 'shaashank.com lists sync'})
    with urllib.request.urlopen(req, timeout=30) as r:
        results = json.load(r).get('results', [])
    tracks = [x for x in results if x.get('wrapperType') == 'track' and x.get('previewUrl')]
    if not tracks:
        raise RuntimeError('No preview found for ' + url)
    return tracks[0]


def clean_title(t):
    return re.sub(r'\s*[\(\[]\s*(From|feat\.?|ft\.?)\b[^\)\]]*[\)\]]', '', t).strip()


def render(rows):
    out = ['{{!-- Generated by scripts/apple_music.py from scripts/artists.json. Edit artists.json, not this file. --}}',
           '<section class="ls-sec" aria-labelledby="ls-artists">',
           '  <div class="ls-sh">', '    <h2 id="ls-artists">Artists I like to listen to</h2>', '  </div>',
           '  <div class="ls-list">']
    for r in rows:
        a, s = html.escape(r['artist']), html.escape(r['song'])
        pic = ('<img class="ls-round" src="{{asset "images/lists/%s"}}" alt="" loading="lazy" decoding="async">' % html.escape(r['photo'])
               if r.get('photo') else
               '<img class="ls-round" src="%s" alt="" width="88" height="88" loading="lazy" decoding="async">' % html.escape(r['art']))
        out.append(
            '    <div class="ls-r ls-song">\n'
            '      <span class="ls-th" style="--th:88px">\n'
            '        <button class="ls-play" type="button" data-preview="%s" aria-label="Play a preview of %s by %s" aria-pressed="false">\n'
            '          %s\n'
            '          <svg class="ls-ring" viewBox="0 0 100 100" aria-hidden="true"><circle cx="50" cy="50" r="47"/></svg>\n'
            '          <span class="ls-pbtn">%s%s</span>\n'
            '        </button>\n'
            '      </span>\n'
            '      <span class="ls-tx"><b>%s</b><span class="ls-sub"><i class="ls-eq" aria-hidden="true"><i></i><i></i><i></i></i>%s</span></span>\n'
            '      <a class="ls-am" href="%s" target="_blank" rel="noopener" aria-label="Listen to %s by %s on Apple Music" title="Listen on Apple Music">%s</a>\n'
            '    </div>' % (html.escape(r['preview']), s, a, pic, PLAY, PAUSE, a, s, html.escape(r['link']), s, a, GO))
    out += ['  </div>', '</section>', '']
    return '\n'.join(out)


def main():
    rows = []
    for item in json.loads(CONFIG.read_text()):
        t = lookup(item['apple'])
        rows.append({'artist': item['artist'], 'song': clean_title(t['trackName']), 'preview': t['previewUrl'],
                     'art': t['artworkUrl100'].replace('100x100bb', '300x300bb'), 'photo': item.get('photo'),
                     'link': item['apple']})
    new = render(rows)
    old = OUT.read_text() if OUT.exists() else ''
    if new != old:
        OUT.write_text(new)
        print('Updated %s with %d songs.' % (OUT.name, len(rows)))
    else:
        print('No change.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
